#!/usr/bin/env python3
"""학종 엔진 v0.1 — 구조 파서 + 제도 필터 (08 설계 §5-2).

판정하지 않는다. 이 모듈은 결정론 단계(①구조 분리 ②제도 필터)만 담당하고,
LLM 요소 매핑(③)은 별도 배치 스크립트에서 이 출력물을 소비한다.

사용: python3 engine/hakjong.py  (내장 샘플 학생부로 데모)
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CRITERIA = json.load(open(os.path.join(ROOT, 'data/db/hakjong_criteria.json'), encoding='utf-8'))['criteria']

# 항목 헤더(나이스 학생부 표기 관례)
섹션패턴 = [
    ('자율활동', r'자율[·\s]?활동|자율·자치활동'),
    ('동아리활동', r'동아리\s?활동'),
    ('진로활동', r'진로\s?활동'),
    ('봉사활동', r'봉사\s?활동'),
    ('수상경력', r'수상\s?경력'),
    ('독서활동', r'독서\s?활동\s?상황|독서\s?활동'),
    ('세특', r'세부능력\s?및\s?특기사항|세특'),
    ('행특', r'행동특성\s?및\s?종합의견|행특'),
]

# 제도 필터 — 02 출처검증에서 확정된 대입 미반영 항목(2024학년도 대입 개편 이후)
미반영규칙 = [
    ('자율동아리', r'자율\s?동아리', '자율동아리는 대입 미반영 — 정규 동아리 활동으로 어필해야 함'),
    ('개인봉사', r'개인\s?계획.{0,14}봉사|개인\s?봉사', '개인 계획 봉사활동은 대입 미반영 — 학교 교육계획 봉사만 반영'),
    ('수상경력', r'수상\s?경력|교내\s?대회.{0,4}수상', '수상경력은 대입 미제공 — 세특·활동 기술로 역량을 보여야 함'),
    ('독서상황', r'독서\s?활동\s?상황', '독서활동상황은 대입 미제공 — 독서 기반 탐구는 세특에 녹여야 반영'),
]


def parse(text):
    """학생부 텍스트 → 섹션별 항목 리스트.

    섹션 경계는 줄머리 헤더만 인정한다 — 본문 중간의 '개인봉사활동' 같은
    언급을 경계로 오인해 세그먼트를 쪼개면 첫 줄 제거 로직이 내용을 삭제한다.
    """
    marks = []
    for 이름, pat in 섹션패턴:
        for m in re.finditer(r'(?m)^[ \t\[<(•\-]*(?:' + pat + ')', text):
            marks.append((m.start(), 이름))
    marks.sort()
    marks.append((len(text), '_END'))
    out = {}
    for i, (pos, 이름) in enumerate(marks[:-1]):
        seg = text[pos:marks[i + 1][0]]
        body = re.sub(r'^[^\n:：]*[:：]?', '', seg, count=1).strip()
        if body:
            out.setdefault(이름, []).append(body)
    return out


# 섹션 자체가 대입 미제공인 항목 — 헤더가 분리돼 본문에 키워드가 안 남으므로 섹션명으로 태깅
섹션미반영 = {
    '수상경력': '수상경력은 대입 미제공 — 세특·활동 기술로 역량을 보여야 함',
    '독서활동': '독서활동상황은 대입 미제공 — 독서 기반 탐구는 세특에 녹여야 반영',
}


def 제도필터(sections):
    """미반영 항목 태깅 — 활동 원문은 남기되 경고를 붙인다(삭제하지 않음)."""
    경고 = []
    for 이름, msg in 섹션미반영.items():
        if 이름 in sections:
            경고.append({'섹션': 이름, '태그': 이름 if 이름 != '독서활동' else '독서상황',
                         '경고': msg, '발췌': sections[이름][0][:60]})
    for 이름, 항목들 in sections.items():
        for 본문 in 항목들:
            for 태그, pat, msg in 미반영규칙:
                if re.search(pat, 본문):
                    경고.append({'섹션': 이름, '태그': 태그, '경고': msg,
                                 '발췌': 본문[:60]})
    return 경고


def build_llm_input(sections, 경고, universities=('ajou',)):
    """③ LLM 요소 매핑 배치 입력 생성 — 점수 필드가 없는 출력 스키마 강제."""
    사전 = [c for c in CRITERIA if c['university_id'] in universities or c['tier'] == 'B']
    return {
        'instruction': ('아래 학생부 활동을 각 대학의 공표 평가요소에 매핑하고 강점/공백만 기술하라. '
                        '점수·등급·합불 표현 금지. 미반영 태그가 붙은 활동은 근거로 쓰지 말 것.'),
        'output_schema': {'요소분석': [{'대학': '', '요소': '', '강점': [], '공백': []}]},
        '평가요소사전': 사전, '학생부': sections, '미반영경고': 경고,
    }


if __name__ == '__main__':
    샘플 = """
자율활동: 학급 자치회 부회장으로 교실 환경개선 프로젝트 주도, 또래 멘토링 운영.
동아리활동: (정규) 물리탐구반 — 아두이노 기반 진자 주기 측정 실험 설계. 자율동아리 코딩클럽에서 파이썬 학습.
진로활동: 반도체 공정 직업인 특강 후 웨이퍼 수율 주제 탐구 보고서 작성.
봉사활동: 학교 교육계획에 따른 도서관 사서도우미 32시간. 개인 계획 요양원 봉사 20시간.
세특: [물리학Ⅰ] 단진자 실험에서 공기저항 보정을 시도하고 오차 분석을 심화함. [수학Ⅱ] 미분을 이용한 최적화 문제를 반도체 수율에 연결.
행특: 끈기 있게 탐구를 지속하며 급우들을 배려함.
"""
    sec = parse(샘플)
    경고 = 제도필터(sec)
    print('◆ 섹션:', {k: len(v) for k, v in sec.items()})
    print('◆ 제도 경고:')
    for w in 경고:
        print(f"  [{w['태그']}] {w['섹션']} — {w['경고']} (발췌: {w['발췌'][:30]}…)")
    llm = build_llm_input(sec, 경고)
    print('◆ LLM 배치 입력 키:', list(llm.keys()), '| 사전', len(llm['평가요소사전']), '건')
    print("※ 출력 스키마에 점수·합불 필드 없음 — 설계 대원칙 1 준수")
